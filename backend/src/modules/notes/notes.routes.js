const router = require('express').Router();
const controller = require('./notes.controller');
const collections = require('./notesCollection.controller');
const { requireAuth, requireRole, optionalAuth } = require('../auth/auth.middleware');
const { upload } = require('./notes.upload');
const { thumbnailUpload } = require('../../utils/thumbnailUpload');
router.get('/', optionalAuth, controller.list);
router.get('/collections', optionalAuth, collections.list);
router.get('/collections/admin', requireAuth, requireRole('admin'), collections.adminList);
router.get('/collections/:id', optionalAuth, collections.detail);
router.post('/collections', requireAuth, requireRole('admin'), collections.create);
router.patch('/collections/:id', requireAuth, requireRole('admin'), collections.update);
router.delete('/collections/:id', requireAuth, requireRole('admin'), collections.remove);
router.post('/collections/:id/thumbnail', requireAuth, requireRole('admin'), thumbnailUpload, collections.uploadThumbnail);
router.delete('/collections/:id/thumbnail', requireAuth, requireRole('admin'), collections.removeThumbnail);
router.get('/admin', requireAuth, requireRole('admin'), controller.adminList);
router.get('/admin/:id', requireAuth, requireRole('admin'), controller.adminDetail);
router.get('/:id', optionalAuth, controller.detail);
router.post('/:id/checkout', requireAuth, requireRole('student'), controller.checkout);
router.post('/:id/checkout/verify', requireAuth, requireRole('student'), controller.verifyPayment);
router.post('/', requireAuth, requireRole('admin'), upload.single('file'), controller.create);
router.post('/:id/replace-pdf', requireAuth, requireRole('admin'), upload.single('file'), controller.replacePdf);
router.post('/:id/thumbnail', requireAuth, requireRole('admin'), thumbnailUpload, controller.uploadThumbnail);
router.delete('/:id/thumbnail', requireAuth, requireRole('admin'), controller.removeThumbnail);
router.patch('/:id', requireAuth, requireRole('admin'), controller.update);
router.delete('/:id', requireAuth, requireRole('admin'), controller.remove);
module.exports = router;
